"""
문제
1에서부터 6까지의 눈을 가진 3개의 주사위를 던져서 다음과 같은 규칙에 따라 상금을 받는 게임이 있다.

같은 눈이 3개가 나오면 10,000원+(같은 눈)×1,000원의 상금을 받게 된다.
같은 눈이 2개만 나오는 경우에는 1,000원+(같은 눈)×100원의 상금을 받게 된다.
모두 다른 눈이 나오는 경우에는 (그 중 가장 큰 눈)×100원의 상금을 받게 된다.
예를 들어, 3개의 눈 3, 3, 6이 주어지면 상금은 1,000+3×100으로 계산되어 1,300원을 받게 된다. 또 3개의 눈이 2, 2, 2로 주어지면 10,000+2×1,000 으로 계산되어 12,000원을 받게 된다. 3개의 눈이 6, 2, 5로 주어지면 그중 가장 큰 값이 6이므로 6×100으로 계산되어 600원을 상금으로 받게 된다.

3개 주사위의 나온 눈이 주어질 때, 상금을 계산하는 프로그램을 작성 하시오.

입력
첫째 줄에 3개의 눈이 빈칸을 사이에 두고 각각 주어진다.

출력
첫째 줄에 게임의 상금을 출력 한다.
"""

A, B, C = map(int, input().split())

if A == B == C:
    print(10000 + (A * 1000))
elif A == B or B == C or A == C:
    if A == B:
        print(1000 + (A * 100))
    elif B == C:
        print(1000 + (B * 100))
    elif A == C:
        print(1000 + (A * 100))
elif A != B != C:
    print(max(A, B, C) * 100)


# 리스트로 받아서 정렬하기
nums = sorted(list(map(int, input().split())))  # 예: [3, 3, 6]
A, B, C = nums

if A == C:  # 정렬했는데 양 끝이 같다면 세 개 다 같은 것!
    print(10000 + A * 1000)
elif A == B or B == C:  # 정렬했으니 가운데(B)는 무조건 겹치는 숫자가 됩니다.
    print(1000 + B * 100)
else:  # 정렬했으니 가장 큰 숫자는 무조건 마지막(C)입니다.
    print(C * 100)

# set 을 이용한 방식

dice = list(map(int, input().split()))
unique_dice = set(dice)  # 중복 제거
count = len(unique_dice)  # 남은 종류의 개수

if count == 1:
    # 종류가 1개다 = 3개가 다 똑같다
    print(10000 + dice[0] * 1000)
elif count == 2:
    # 종류가 2개다 = 2개는 같고 1개는 다르다
    # 어떤 게 중복인지 찾으려면? 전체 합에서 set의 합을 이용하거나 정렬을 씁니다.
    # 가장 쉬운 건, 정렬했을 때 '가운데 값'은 무조건 중복된 값입니다!
    dice.sort()
    print(1000 + dice[1] * 100)
else:
    # 종류가 3개다 = 다 다르다
    print(max(dice) * 100)
